package dns

import (
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"hproxy/config"
)

// Dnsmasq 实现 DNSProvider 接口
//
// 设计目标（取代外部 sync 脚本）：
//  1. 直接输出 dnsmasq 合法语法 "address=/domain/ip"（无空格）
//  2. 原子写入：同目录临时文件 -> rename，绝不出现半截文件
//  3. 落盘前用 dnsmasq --test 预检，失败则整批丢弃、保持旧文件不动
//  4. 内容无变化不写盘、不重启
//  5. 可选 backup_file：规则集为空（上游抓取失败）时回退到上次正常内容，
//     避免一次异常把全屋 DNS 规则清空；需要真正清空时删掉 backup_file 即可
type Dnsmasq struct {
	ConfFile    string // 主配置（可选，留空表示不维护 include）
	OutputFile  string // dnsmasq 读取的规则文件
	ReloadCmd   string // 重载命令
	TestBin     string // dnsmasq 可执行文件，默认 /usr/sbin/dnsmasq
	BackupFile  string // 上次正常内容备份（可选）
	lastDomains map[string]string
	lastModTime time.Time
}

// NewDnsmasq 创建 Dnsmasq 实例
func NewDnsmasq(cfg map[string]interface{}) (*Dnsmasq, error) {
	d := &Dnsmasq{
		TestBin:     "/usr/sbin/dnsmasq",
		lastDomains: make(map[string]string),
	}
	if v, ok := cfg["conf_file"]; ok {
		d.ConfFile, _ = v.(string)
	}
	if v, ok := cfg["output_file"]; ok {
		d.OutputFile, _ = v.(string)
	}
	if v, ok := cfg["reload_cmd"]; ok {
		d.ReloadCmd, _ = v.(string)
	}
	if v, ok := cfg["test_bin"]; ok {
		if s, _ := v.(string); s != "" {
			d.TestBin = s
		}
	}
	if v, ok := cfg["backup_file"]; ok {
		d.BackupFile, _ = v.(string)
	}
	if d.OutputFile == "" {
		return nil, fmt.Errorf("dnsmasq: output_file 未配置")
	}
	return d, nil
}

func (d *Dnsmasq) Name() string {
	return "dnsmasq"
}

// UpdateDomains 更新域名配置，返回是否有实际变更（需重载）
func (d *Dnsmasq) UpdateDomains(domains map[string]string) (bool, error) {
	if d.compareDomains(domains) && !d.isConfigModified() {
		config.DebugLog("[Dnsmasq] 域名无变化，跳过更新")
		return false, nil
	}

	content := d.render(domains)

	// 空规则集保护：上游抓取失败时不要把现有规则清空
	if len(domains) == 0 && d.BackupFile != "" {
		if old, err := os.ReadFile(d.BackupFile); err == nil && len(bytesTrimSpace(old)) > 0 {
			log.Printf("[Dnsmasq] 规则集为空，回退到备份 %s", d.BackupFile)
			content = string(old)
		}
	}

	if err := d.writeAtomic([]byte(content)); err != nil {
		log.Printf("[Dnsmasq] 写入失败，保持旧配置: %v", err)
		return false, err
	}

	d.lastDomains = make(map[string]string, len(domains))
	for k, v := range domains {
		d.lastDomains[k] = v
	}
	if info, err := os.Stat(d.OutputFile); err == nil {
		d.lastModTime = info.ModTime()
	}

	log.Printf("[Dnsmasq] 已更新 %d 条域名到 %s", len(domains), d.OutputFile)
	return true, d.ensureConfig()
}

// render 生成规则文件内容（域名排序保证输出稳定）
func (d *Dnsmasq) render(domains map[string]string) string {
	names := make([]string, 0, len(domains))
	for name := range domains {
		names = append(names, name)
	}
	sort.Strings(names)

	now := time.Now().Format("2006-01-02 15:04:05")
	var sb strings.Builder
	fmt.Fprintf(&sb, "# Auto-generated by hproxy @ %s\n", now)
	fmt.Fprintf(&sb, "# Total: %d domains\n", len(names))
	fmt.Fprintf(&sb, "# Last update: %s\n", now)
	for _, name := range names {
		fmt.Fprintf(&sb, "address=/%s/%s\n", name, domains[name])
	}
	return sb.String()
}

// writeAtomic 原子写入 + dnsmasq --test 预检
func (d *Dnsmasq) writeAtomic(content []byte) error {
	dir := filepath.Dir(d.OutputFile)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}

	tmp, err := os.CreateTemp(dir, ".hproxy-dns-*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer func() {
		tmp.Close()
		os.Remove(tmpName)
	}()

	if _, err := tmp.Write(content); err != nil {
		return err
	}
	if err := tmp.Chmod(0644); err != nil {
		return err
	}
	if err := tmp.Sync(); err != nil {
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}

	// 预检：把候选文件 include 进一个最小配置里试运行
	if err := d.validate(tmpName); err != nil {
		return err
	}

	if err := os.Rename(tmpName, d.OutputFile); err != nil {
		return err
	}

	// 备份（best-effort，失败不影响主流程）
	if d.BackupFile != "" {
		if e := os.MkdirAll(filepath.Dir(d.BackupFile), 0755); e == nil {
			if e := os.WriteFile(d.BackupFile, content, 0644); e != nil {
				config.DebugLog("[Dnsmasq] 备份失败 %s: %v", d.BackupFile, e)
			}
		}
	}
	return nil
}

// validate 用 dnsmasq --test 校验候选文件
func (d *Dnsmasq) validate(candidate string) error {
	testCfg, err := os.CreateTemp(filepath.Dir(d.OutputFile), ".hproxy-test-*.conf")
	if err != nil {
		return err
	}
	testName := testCfg.Name()
	defer os.Remove(testName)

	cfgBody := fmt.Sprintf("port=0\nno-resolv\nno-hosts\nconf-file=%s\n", candidate)
	if _, err := testCfg.WriteString(cfgBody); err != nil {
		testCfg.Close()
		return err
	}
	testCfg.Close()

	out, err := exec.Command(d.TestBin, "--test", "-C", testName).CombinedOutput()
	if err != nil {
		return fmt.Errorf("dnsmasq --test 失败: %s", strings.TrimSpace(string(out)))
	}
	return nil
}

func (d *Dnsmasq) compareDomains(domains map[string]string) bool {
	if len(domains) != len(d.lastDomains) {
		return false
	}
	for domain, ip := range domains {
		lastIP, ok := d.lastDomains[domain]
		if !ok || lastIP != ip {
			return false
		}
	}
	return true
}

func (d *Dnsmasq) isConfigModified() bool {
	info, err := os.Stat(d.OutputFile)
	if err != nil {
		return true
	}
	return info.ModTime().After(d.lastModTime)
}

func (d *Dnsmasq) ensureConfig() error {
	if d.ConfFile == "" {
		return nil
	}
	data, err := os.ReadFile(d.ConfFile)
	if err != nil {
		log.Printf("[Dnsmasq] 读取主配置失败 %s: %v", d.ConfFile, err)
		return err
	}
	content := string(data)
	if strings.Contains(content, d.OutputFile) {
		return nil
	}
	f, err := os.OpenFile(d.ConfFile, os.O_APPEND|os.O_WRONLY, 0644)
	if err != nil {
		log.Printf("[Dnsmasq] 打开主配置失败 %s: %v", d.ConfFile, err)
		return err
	}
	defer f.Close()
	if _, err = f.WriteString("\nconf-file=" + d.OutputFile + "\n"); err != nil {
		log.Printf("[Dnsmasq] 写入主配置失败 %s: %v", d.ConfFile, err)
		return err
	}
	return f.Sync()
}

func (d *Dnsmasq) Reload() error {
	if d.ReloadCmd == "" {
		config.DebugLog("[Dnsmasq] 未配置 reload_cmd，跳过重载")
		return nil
	}
	cmd := exec.Command("sh", "-c", d.ReloadCmd)
	if err := cmd.Run(); err != nil {
		config.DebugLog("[Dnsmasq] 重载失败: %v", err)
	}
	config.DebugLog("[Dnsmasq] 已重载")
	return nil
}

func bytesTrimSpace(b []byte) []byte {
	return []byte(strings.TrimSpace(string(b)))
}
